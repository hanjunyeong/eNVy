"""Trusted analysis worker. Uploaded bytes are data, never an executable command."""
import argparse
import json
import math
import os
from pathlib import Path
import sys
import time
from scan_config import MAX_FILE_SIZE

STAGES = {
    "read_file", "load_dependencies", "pe_validation", "metadata",
    "model_load", "features_and_prediction", "result_write",
}


class StageReporter:
    """Publish a small atomic diagnostic file; reporting never changes a score."""
    def __init__(self, result_path):
        self.path = result_path.with_name("stage.json")
        self.started = time.monotonic()

    def __call__(self, stage):
        if stage not in STAGES:
            return
        payload = {"stage": stage, "elapsed_seconds": round(time.monotonic() - self.started, 3)}
        temporary = self.path.with_suffix(".tmp")
        try:
            temporary.write_text(json.dumps(payload, allow_nan=False), encoding="utf-8")
            os.replace(temporary, self.path)
        except OSError:
            # Diagnostics must not prevent a valid analysis result.
            pass


def analyze(data, model_path, report_stage=lambda stage: None):
    # All third-party parsing and inference imports happen in the worker.
    report_stage("load_dependencies")
    import pefile
    from pe_details import analyze_pe

    report_stage("pe_validation")
    try:
        pe = pefile.PE(data=data, fast_load=True)
    except pefile.PEFormatError:
        return {"ok": False, "status_code": 400, "detail": "분석 가능한 Windows PE 파일이 아닙니다."}
    details = None
    details_error = None
    report_stage("metadata")
    try:
        details = analyze_pe(data, pe)
    except Exception:
        details_error = "상세정보 일부를 읽지 못했습니다. 모델 판정과 별도로 확인해 주세요."
    finally:
        pe.close()
    report_stage("model_load")
    try:
        import lightgbm as lgb
        from thrember.model import predict_sample
        model = lgb.Booster(model_file=str(model_path))
        # predict_sample calls Booster.predict, which reads these prediction
        # parameters. Limit inference threads without changing model trees.
        model.params["num_threads"] = 1
    except Exception:
        return {"ok": False, "status_code": 503, "detail": "분석 모델을 불러오지 못했습니다. 모델 파일과 설치 패키지를 확인해 주세요."}
    report_stage("features_and_prediction")
    try:
        score = float(predict_sample(model, data))
        if not math.isfinite(score) or not 0 <= score <= 1:
            raise ValueError("Invalid score")
    except Exception:
        return {"ok": False, "status_code": 422, "detail": "이 파일의 특징 추출 또는 모델 분석에 실패했습니다."}
    return {"ok": True, "result": {
        "score": score, "verdict": "악성으로 의심" if score >= 0.5 else "정상으로 추정",
        "details": details, "details_error": details_error,
    }}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", required=True, type=Path)
    parser.add_argument("--result", required=True, type=Path)
    parser.add_argument("--input", required=True, type=Path)
    args = parser.parse_args()
    report_stage = StageReporter(args.result)
    # Only the analysis process reads the whole file for thrember/pefile.
    # The input path is generated by the server, never the uploaded filename.
    report_stage("read_file")
    with args.input.open("rb") as source:
        data = source.read(MAX_FILE_SIZE + 1)
    if not data:
        payload = {"ok": False, "status_code": 400, "detail": "빈 파일입니다."}
    elif len(data) > MAX_FILE_SIZE:
        payload = {"ok": False, "status_code": 413, "detail": "허용한 파일 크기를 초과했습니다."}
    else:
        try:
            payload = analyze(data, args.model, report_stage)
        except Exception:
            payload = {"ok": False, "status_code": 500, "detail": "파일 분석 중 오류가 발생했습니다."}
    # Publish only complete JSON. The server reads it after this process exits.
    report_stage("result_write")
    temporary = args.result.with_suffix(".tmp")
    temporary.write_text(json.dumps(payload, ensure_ascii=False, allow_nan=False), encoding="utf-8")
    os.replace(temporary, args.result)


if __name__ == "__main__":
    main()
