import os
from dataclasses import dataclass, field
from pathlib import Path


@dataclass
class Settings:
    data_dir: Path = field(default_factory=lambda: Path(os.getenv("DATA_DIR", "./data")).resolve())
    model_path: Path = field(default_factory=lambda: Path(os.getenv("MODEL_PATH", "./models/EMBER2024_PE.model")).resolve())
    database_url: str = field(default_factory=lambda: os.getenv("DATABASE_URL", "sqlite:///./data/envy.db"))
    broker_url: str = field(default_factory=lambda: os.getenv("BROKER_URL", "redis://broker:6379/0"))
    cache_url: str = field(default_factory=lambda: os.getenv("CACHE_URL", "redis://cache:6379/0"))
    inference_url: str = field(default_factory=lambda: os.getenv("INFERENCE_URL", "http://inference:8001").rstrip("/"))
    pipeline_version: str = field(default_factory=lambda: os.getenv("PIPELINE_VERSION", "envy-pe-v4"))
    max_file_size: int = 300 * 1024 * 1024
    chunk_size: int = 1024 * 1024
    max_pending_jobs: int = 8
    max_concurrent_uploads: int = 2
    soft_timeout: int = 300
    hard_timeout: int = 330
    queue_ttl: int = 1800
    cache_ttl: int = 7 * 86400
    history_days: int = 30
    threshold: float = 0.5

    def pipeline_fingerprint(self):
        """Identify analysis code and installed core dependencies without importing parsers."""
        import hashlib
        from importlib.metadata import PackageNotFoundError, version
        import json
        root = Path(__file__).resolve().parents[1]
        files = {}
        for name in ("envy/config.py", "envy/engine.py", "envy/inference.py", "envy/pe_details.py", "requirements.txt"):
            files[name] = hashlib.sha256((root / name).read_bytes()).hexdigest()
        packages = {}
        for name in ("thrember", "pefile", "numpy", "signify", "lightgbm"):
            try:
                packages[name] = version(name)
            except PackageNotFoundError:
                packages[name] = "not-installed"
        payload = {"files": files, "packages": packages, "pipeline": self.pipeline_version}
        return hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()[:24]

    def model_version(self, model_sha):
        return f"{model_sha}:{self.pipeline_version}:{self.pipeline_fingerprint()}:threshold-{self.threshold:g}"

    def input_path(self, job_id):
        # Job IDs are generated by the API, not filenames or user-chosen paths.
        import re
        if not re.fullmatch(r"[0-9a-f]{32}", job_id):
            raise ValueError("Invalid job ID")
        return self.data_dir / (job_id + ".bin")

    def public(self):
        return {"max_file_size_bytes": self.max_file_size, "max_file_size_label": "300 MiB",
                "scan_timeout_seconds": self.soft_timeout, "hard_timeout_seconds": self.hard_timeout,
                "max_concurrent_scans": 1, "max_pending_jobs": self.max_pending_jobs,
                "queue_enabled": True}
